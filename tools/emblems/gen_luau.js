// Copies the emblem designs from preview/emblems.js (the single source of the geometry) into
// the data block of src/client/UI/Emblem.luau.
//   node tools/emblems/gen_luau.js          -> rewrite the block
//   node tools/emblems/gen_luau.js --check  -> exit 1 if Emblem.luau is out of date
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const FILE = path.join(ROOT, 'src', 'client', 'UI', 'Emblem.luau');
const E = require(path.join(ROOT, 'preview', 'emblems.js'));

const BEGIN = '-- BEGIN EMBLEM DATA';
const END = '-- END EMBLEM DATA';

const num = (v) => {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error('bad number ' + v);
  return String(v); // shortest round-trip form: Luau reads back the identical double
};
const str = (v) => JSON.stringify(v);
const rgb = (c) => `{ ${c.map(num).join(', ')} }`;
const ink = (i) => (Array.isArray(i) ? rgb(i) : str(i));

function op(o) {
  const f = [`t = ${str(o.t)}`];
  if (o.t === 'L') {
    f.push(`x1 = ${num(o.x1)}`, `y1 = ${num(o.y1)}`, `x2 = ${num(o.x2)}`, `y2 = ${num(o.y2)}`, `i = ${ink(o.i)}`);
    if (o.w !== 'n') f.push(`w = ${str(o.w)}`);
    if (!o.c) f.push('c = 0');
  } else if (o.t === 'R') {
    f.push(`x = ${num(o.x)}`, `y = ${num(o.y)}`, `w = ${num(o.w)}`, `h = ${num(o.h)}`, `i = ${ink(o.i)}`);
    if (o.r) f.push(`r = ${num(o.r)}`);
    if (o.s) f.push(`s = ${str(o.s)}`);
    if (o.o) f.push('o = 1');
    if (o.cut) {
      // gradient steps away from the center are only exact along a box's own axes, and a
      // UIStroke's gradient box is uncertain, so anything else must cut through the center
      const c = o.cut;
      if ((c.r % 90 !== 0 || o.s || o.o) && !(c.a === 0.5 && c.b === 1)) throw new Error('off-center cut on a diagonal, ring or outline');
      f.push(`cut = { r = ${num(c.r)}, a = ${num(c.a)}, b = ${num(c.b)} }`);
    }
  } else {
    throw new Error('unknown op ' + o.t);
  }
  return `{ ${f.join(', ')} }`;
}

function def(d, indent) {
  const t = '\t'.repeat(indent);
  const lines = [`{`, `${t}\tc = ${rgb(d.color)},`];
  if (d.ink) lines.push(`${t}\tink = ${rgb(d.ink)},`);
  lines.push(`${t}\tops = {`);
  for (const o of d.ops) lines.push(`${t}\t\t${op(o)},`);
  lines.push(`${t}\t},`, `${t}}`);
  return lines.join('\n');
}

function block() {
  const out = [];
  out.push(`${BEGIN} (generated by tools/emblems/gen_luau.js from preview/emblems.js; do not edit)`);
  out.push(`local INK_MIX = ${num(E.inkMix)}`);
  out.push(`local BONE = ${rgb(E.bone)}`);
  out.push(`local DARK = ${rgb(E.dark)}`);
  out.push('local ORDER: { string } = {');
  for (const id of E.ids) out.push(`\t${str(id)},`);
  out.push('}');
  out.push('local DEFS: { [string]: Def } = {');
  for (const id of E.ids) out.push(`\t[${str(id)}] = ${def(E.defs[id], 1)},`);
  out.push('}');
  out.push(`local FALLBACK: Def = ${def(E.fallback, 0)}`);
  out.push(`local LOGO: Def = ${def(E.logoDef, 0)}`);
  out.push(END);
  return out.join('\n');
}

const src = fs.readFileSync(FILE, 'utf8');
const a = src.indexOf(BEGIN);
const b = src.indexOf(END);
if (a < 0 || b < a) throw new Error('data markers not found in ' + FILE);
const next = src.slice(0, a) + block() + src.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== src) {
    console.error('Emblem.luau is out of date: run node tools/emblems/gen_luau.js');
    process.exit(1);
  }
  console.log('Emblem.luau matches preview/emblems.js');
} else {
  fs.writeFileSync(FILE, next);
  console.log(`wrote ${E.ids.length} emblems + logo into ${path.relative(ROOT, FILE)}`);
}
